-- Visitor funnel. 2026-11-10.
-- Client: src/lib/api/funnel.js · Reading it: supabase/diagnostics/funnel_report.sql
-- Privacy copy: privacy.whatDataWeCollectPara7 (src/i18n/*.json)
--
-- Question this answers: a visitor arrived from search — what did they do
-- before they left or signed up? Search Console stops at the click; this picks
-- up from the first page.
--
-- Privacy shape (the client enforces the same; the server re-checks):
--   - `session` is a random id from the tab's sessionStorage. Not a cookie,
--     not derived from anything about the person, gone when the tab closes.
--   - `user_id` is set ONLY on the account milestones (signup/signin
--     completed, onboarding completed, intent resumed) — never on page views.
--   - `path` is kept only for public catalogue pages (/book, /series, /genre).
--   - `source` is a site name ('search:google', 'ref:alternativeto.net'),
--     never a referring URL or a search query.
--   - No IP address, no user agent, no fingerprint is stored.
--   - Nothing is written under Do Not Track / Global Privacy Control, or from
--     automated browsers (client-side check).
--   - Rows older than 12 months are deleted (prune_funnel_events, scheduled
--     below when pg_cron is available).
--
-- Nobody reads this table through the API: RLS on, no policies, all grants
-- revoked. Read it in the SQL editor (service role / postgres).
--
-- Idempotent.

create table if not exists public.funnel_events (
  id         bigint generated by default as identity primary key,
  session    text        not null,
  event      text        not null,
  page_type  text,
  path       text,
  source     text,
  lang       text,
  device     text,
  props      jsonb       not null default '{}'::jsonb,
  user_id    uuid        references auth.users(id) on delete set null,
  day        date        not null default ((now() at time zone 'utc')::date),
  created_at timestamptz not null default now(),
  constraint funnel_events_event_check check (event in (
    'landing', 'page_view', 'cta_click', 'auth_open', 'auth_submit', 'auth_error',
    'signup_completed', 'signin_completed', 'onboarding_completed', 'intent_resumed',
    'teaser_open', 'teaser_result', 'teaser_save'
  )),
  constraint funnel_events_session_fmt check (session ~ '^[0-9a-f-]{16,64}$'),
  constraint funnel_events_page_type_len check (page_type is null or length(page_type) <= 20),
  constraint funnel_events_path_len check (path is null or length(path) <= 300),
  constraint funnel_events_source_len check (source is null or length(source) <= 80),
  constraint funnel_events_lang_len check (lang is null or length(lang) <= 5),
  constraint funnel_events_device_check check (device is null or device in ('mobile', 'desktop')),
  constraint funnel_events_props_size check (pg_column_size(props) <= 1024)
);

-- One landing per tab session; one signup per account. A reload or a replayed
-- call is a no-op rather than a second row.
create unique index if not exists funnel_events_landing_once
  on public.funnel_events (session) where event = 'landing';
create unique index if not exists funnel_events_signup_once
  on public.funnel_events (user_id) where event = 'signup_completed';
create index if not exists funnel_events_day_idx
  on public.funnel_events (day, event);
create index if not exists funnel_events_session_idx
  on public.funnel_events (session, created_at);

alter table public.funnel_events enable row level security;
revoke all on public.funnel_events from anon, authenticated;

comment on table public.funnel_events is
  '2026-11-10: signed-out visitor funnel (landing → CTA → sign-in window → account). No IPs, no user agents; user_id only on account milestones. Read with supabase/diagnostics/funnel_report.sql.';

-- ── Write ─────────────────────────────────────────────────────────────────────
create or replace function public.log_funnel_event (
  p_session   text,
  p_event     text,
  p_page_type text  DEFAULT NULL,
  p_path      text  DEFAULT NULL,
  p_source    text  DEFAULT NULL,
  p_lang      text  DEFAULT NULL,
  p_device    text  DEFAULT NULL,
  p_props     jsonb DEFAULT '{}'::jsonb
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
declare
  v_uid     uuid := auth.uid();
  v_user    uuid := null;
  v_created timestamptz;
  v_today   integer;
  v_props   jsonb := '{}'::jsonb;
  v_key     text;
begin
  if p_session is null or p_session !~ '^[0-9a-f-]{16,64}$' then return; end if;
  if p_event not in (
    'landing', 'page_view', 'cta_click', 'auth_open', 'auth_submit', 'auth_error',
    'signup_completed', 'signin_completed', 'onboarding_completed', 'intent_resumed',
    'teaser_open', 'teaser_result', 'teaser_save'
  ) then return; end if;

  -- A tab that sends more than this in a day is a script, not a reader.
  select count(*) into v_today
    from public.funnel_events
   where session = p_session and day = (now() at time zone 'utc')::date;
  if v_today >= 300 then return; end if;

  -- Account milestones are the only rows tied to an account.
  if p_event in ('signup_completed', 'signin_completed', 'onboarding_completed', 'intent_resumed') then
    if v_uid is null then return; end if;
    v_user := v_uid;
    if p_event = 'signup_completed' then
      -- A genuinely new account only: replaying the call later records nothing.
      select created_at into v_created from auth.users where id = v_uid;
      if v_created is null or v_created < now() - interval '2 days' then return; end if;
    end if;
  end if;

  -- Whitelisted props only, primitives only, short strings.
  if jsonb_typeof(p_props) = 'object' then
    for v_key in select jsonb_object_keys(p_props) loop
      if v_key in ('cta', 'from', 'mode', 'method', 'kind', 'type', 'count', 'cached', 'src', 'land')
         and jsonb_typeof(p_props -> v_key) in ('string', 'number', 'boolean') then
        v_props := v_props || jsonb_build_object(
          v_key,
          case when jsonb_typeof(p_props -> v_key) = 'string'
               then to_jsonb(left(p_props ->> v_key, 60))
               else p_props -> v_key end
        );
      end if;
    end loop;
  end if;

  insert into public.funnel_events (session, event, page_type, path, source, lang, device, props, user_id)
  values (
    p_session,
    p_event,
    left(nullif(p_page_type, ''), 20),
    -- Same rule as the client: only catalogue paths survive.
    case when p_path ~ '^/(book|series|genre|genres)(/|$)' then left(p_path, 300) end,
    left(nullif(p_source, ''), 80),
    left(nullif(p_lang, ''), 5),
    case when p_device in ('mobile', 'desktop') then p_device end,
    v_props,
    v_user
  )
  on conflict do nothing;
end;
$function$;

revoke execute on function public.log_funnel_event(text, text, text, text, text, text, text, jsonb) from public;
grant  execute on function public.log_funnel_event(text, text, text, text, text, text, text, jsonb) to anon, authenticated;

-- ── Retention: 12 months ─────────────────────────────────────────────────────
create or replace function public.prune_funnel_events()
  RETURNS integer
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
  with gone as (
    delete from public.funnel_events
     where created_at < now() - interval '12 months'
    returning 1
  )
  select count(*)::integer from gone;
$function$;

revoke execute on function public.prune_funnel_events() from public, anon, authenticated;

-- Weekly prune when pg_cron is installed. Without it, run
--   select public.prune_funnel_events();
-- by hand now and then (the privacy page promises 12 months).
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname = 'prune_funnel_events';
    perform cron.schedule('prune_funnel_events', '17 4 * * 1', 'select public.prune_funnel_events();');
  end if;
end;
$$;

-- ── Reading ───────────────────────────────────────────────────────────────────
-- One row per signed-out session: where it came from, where it landed, how far
-- it got. Not granted to the API roles.
create or replace view public.funnel_sessions as
  select
    l.session,
    l.day,
    l.source,
    l.page_type                                                         as landing_type,
    l.path                                                              as landing_path,
    l.lang,
    l.device,
    (select count(*) from public.funnel_events e
      where e.session = l.session and e.event = 'page_view')            as pages_after,
    exists (select 1 from public.funnel_events e
             where e.session = l.session and e.event = 'cta_click')     as clicked_cta,
    exists (select 1 from public.funnel_events e
             where e.session = l.session and e.event = 'teaser_open')   as asked_oracle,
    exists (select 1 from public.funnel_events e
             where e.session = l.session and e.event = 'auth_open')     as opened_auth,
    exists (select 1 from public.funnel_events e
             where e.session = l.session and e.event = 'auth_submit')   as submitted_auth,
    exists (select 1 from public.funnel_events e
             where e.session = l.session
               and e.event in ('signup_completed', 'signin_completed')) as got_account,
    (select max(e.created_at) from public.funnel_events e
      where e.session = l.session) - l.created_at                       as time_on_site
  from public.funnel_events l
  where l.event = 'landing';

revoke all on public.funnel_sessions from anon, authenticated;

comment on view public.funnel_sessions is
  'One row per signed-out visit (landing). Signups that finished in another tab are not here — see funnel_report.sql §4, which counts them by first-touch source.';
