-- Share tracking. 2026-11-25 (v0.74).
-- Spec: claude/share-tracking-v1-spec.md (project docs)
-- Client: src/lib/share/shareTracking.js · Unfurls: netlify/edge-functions/og-prerender.js
-- Reading it: supabase/diagnostics/share_report.sql
-- Privacy copy: privacy.whatDataWeCollectPara8 (src/i18n/*.json)
--
-- Questions this answers: what gets shared, to which app, did the link get
-- posted (a link-preview crawler fetched it), and did anyone open it.
--
-- Every shared link carries ?s=<8-char token>. The token is made in the
-- browser at the moment of sharing (so window.open / navigator.share stay
-- inside the tap) and registered here with log_share().
--
-- Privacy shape (the client enforces the same; the server re-checks):
--   - `shares.sharer_id` is the signed-in sharer, or null. Deleted with the account.
--   - A hit never says who opened the link: no user id, no session id, no IP,
--     no user agent. Only: which token, unfurl or click, which preview app
--     (unfurls), the referring site's host (clicks), and signed in or not.
--   - A sharer opening their own link is not counted.
--   - Nothing is written under Do Not Track / Global Privacy Control or from
--     automated browsers (client-side check).
--   - Hits older than 12 months are deleted (prune_share_hits).
--
-- Nobody reads these tables through the API: RLS on, no policies, all grants
-- revoked. Writes only through the two security-definer functions below.
--
-- Idempotent.

create table if not exists public.shares (
  id           text        primary key,
  sharer_id    uuid        references auth.users(id) on delete cascade,
  entity_type  text        not null,
  entity_key   text        not null,
  channel      text        not null,
  surface      text        not null default 'page',
  locale       text,
  day          date        not null default ((now() at time zone 'utc')::date),
  created_at   timestamptz not null default now(),
  constraint shares_id_fmt check (id ~ '^[0-9A-Za-z]{8}$'),
  constraint shares_entity_type_check check (entity_type in (
    'book', 'series', 'list', 'plan', 'club', 'profile', 'session', 'site'
  )),
  constraint shares_entity_key_len check (length(entity_key) <= 200),
  constraint shares_channel_check check (channel in (
    'x', 'whatsapp', 'telegram', 'facebook', 'bluesky', 'threads', 'reddit',
    'linkedin', 'email', 'copy', 'native', 'other'
  )),
  constraint shares_surface_check check (surface in ('page', 'moment_link', 'moment_image')),
  constraint shares_locale_check check (locale is null or locale in ('en', 'es'))
);

create index if not exists shares_created_idx on public.shares (created_at desc);
create index if not exists shares_entity_idx  on public.shares (entity_type, entity_key);
create index if not exists shares_sharer_day_idx on public.shares (sharer_id, day) where sharer_id is not null;
create index if not exists shares_anon_day_idx   on public.shares (day) where sharer_id is null;

create table if not exists public.share_hits (
  id            bigint      generated by default as identity primary key,
  share_id      text        not null references public.shares(id) on delete cascade,
  kind          text        not null,
  agent         text,
  referrer_host text,
  signed_in     boolean,
  day           date        not null default ((now() at time zone 'utc')::date),
  created_at    timestamptz not null default now(),
  constraint share_hits_kind_check check (kind in ('unfurl', 'click')),
  constraint share_hits_agent_check check (agent is null or agent in (
    'facebook', 'whatsapp', 'x', 'telegram', 'slack', 'discord', 'linkedin',
    'bluesky', 'reddit', 'imessage', 'other_preview'
  )),
  constraint share_hits_ref_fmt check (referrer_host is null or referrer_host ~ '^[a-z0-9.-]{1,100}$')
);

create index if not exists share_hits_share_idx   on public.share_hits (share_id, kind);
create index if not exists share_hits_created_idx on public.share_hits (created_at desc);
create index if not exists share_hits_share_day_idx on public.share_hits (share_id, day);

alter table public.shares     enable row level security;
alter table public.share_hits enable row level security;
revoke all on public.shares     from anon, authenticated;
revoke all on public.share_hits from anon, authenticated;

comment on table public.shares is
  '2026-11-25 (v0.74): one row per share from ShareModal / ShareMomentModal. sharer_id null for signed-out shares. Read with supabase/diagnostics/share_report.sql.';
comment on table public.share_hits is
  '2026-11-25 (v0.74): what a shared link brought back — link-preview fetches (unfurl) and visits (click). Never who: no user, session, IP or user agent.';

-- ── Write: a share ───────────────────────────────────────────────────────────
create or replace function public.log_share (
  p_id          text,
  p_entity_type text,
  p_entity_key  text,
  p_channel     text,
  p_surface     text DEFAULT 'page',
  p_locale      text DEFAULT NULL
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
declare
  v_uid   uuid := auth.uid();
  v_today integer;
begin
  if p_id is null or p_id !~ '^[0-9A-Za-z]{8}$' then return; end if;
  if p_entity_type not in ('book', 'series', 'list', 'plan', 'club', 'profile', 'session', 'site') then return; end if;
  if p_channel not in ('x', 'whatsapp', 'telegram', 'facebook', 'bluesky', 'threads', 'reddit',
                       'linkedin', 'email', 'copy', 'native', 'other') then return; end if;
  if coalesce(p_surface, 'page') not in ('page', 'moment_link', 'moment_image') then return; end if;
  if p_entity_key is null or length(p_entity_key) = 0 then return; end if;

  -- Caps: no reader shares 200 things a day, and signed-out shares (series
  -- pages) are a trickle. Past either, it is a script.
  if v_uid is not null then
    select count(*) into v_today from public.shares
     where sharer_id = v_uid and day = (now() at time zone 'utc')::date;
    if v_today >= 200 then return; end if;
  else
    select count(*) into v_today from public.shares
     where sharer_id is null and day = (now() at time zone 'utc')::date;
    if v_today >= 2000 then return; end if;
  end if;

  insert into public.shares (id, sharer_id, entity_type, entity_key, channel, surface, locale)
  values (
    p_id,
    v_uid,
    p_entity_type,
    left(p_entity_key, 200),
    p_channel,
    coalesce(p_surface, 'page'),
    case when p_locale in ('en', 'es') then p_locale end
  )
  on conflict (id) do nothing;
end;
$function$;

revoke execute on function public.log_share(text, text, text, text, text, text) from public;
grant  execute on function public.log_share(text, text, text, text, text, text) to anon, authenticated;

-- ── Write: a hit on a shared link ────────────────────────────────────────────
-- 'click'  — from the SPA, anon or authenticated.
-- 'unfurl' — only from og-prerender.js, which calls with the service role. A
--            browser cannot claim to be WhatsApp's preview crawler.
create or replace function public.log_share_hit (
  p_share     text,
  p_kind      text,
  p_agent     text    DEFAULT NULL,
  p_ref_host  text    DEFAULT NULL,
  p_signed_in boolean DEFAULT NULL
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
declare
  v_uid    uuid := auth.uid();
  v_sharer uuid;
  v_found  boolean;
  v_today  integer;
  v_host   text;
begin
  if p_share is null or p_share !~ '^[0-9A-Za-z]{8}$' then return; end if;
  if p_kind not in ('unfurl', 'click') then return; end if;
  if p_kind = 'unfurl' and coalesce(auth.role(), '') <> 'service_role' then return; end if;

  select true, sharer_id into v_found, v_sharer from public.shares where id = p_share;
  -- A token nobody registered: hand-edited, or copied from the modal by hand
  -- and never logged. Nothing to attach it to.
  if v_found is null then return; end if;

  -- The sharer testing their own link is not a reader the share brought.
  if p_kind = 'click' and v_uid is not null and v_uid = v_sharer then return; end if;

  select count(*) into v_today from public.share_hits
   where share_id = p_share and day = (now() at time zone 'utc')::date;
  if v_today >= 500 then return; end if;

  v_host := lower(left(coalesce(p_ref_host, ''), 100));
  if v_host !~ '^[a-z0-9.-]{1,100}$' then v_host := null; end if;

  insert into public.share_hits (share_id, kind, agent, referrer_host, signed_in)
  values (
    p_share,
    p_kind,
    case when p_kind = 'unfurl' and p_agent in (
           'facebook', 'whatsapp', 'x', 'telegram', 'slack', 'discord', 'linkedin',
           'bluesky', 'reddit', 'imessage', 'other_preview')
         then p_agent
         when p_kind = 'unfurl' then 'other_preview' end,
    case when p_kind = 'click' then v_host end,
    case when p_kind = 'click' then coalesce(p_signed_in, v_uid is not null) end
  );
end;
$function$;

revoke execute on function public.log_share_hit(text, text, text, text, boolean) from public;
grant  execute on function public.log_share_hit(text, text, text, text, boolean) to anon, authenticated, service_role;

-- ── Retention: 12 months ─────────────────────────────────────────────────────
-- Same window as funnel_events, so share → signup joins never lose one side.
create or replace function public.prune_share_hits()
  RETURNS integer
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
  with gone as (
    delete from public.share_hits
     where created_at < now() - interval '12 months'
    returning 1
  )
  select count(*)::integer from gone;
$function$;

revoke execute on function public.prune_share_hits() from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname = 'prune_share_hits';
    perform cron.schedule('prune_share_hits', '23 4 * * 1', 'select public.prune_share_hits();');
  end if;
end;
$$;
